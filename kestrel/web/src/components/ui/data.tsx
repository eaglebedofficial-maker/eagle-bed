export function NotConfigured({ provider, message, className }: { provider?: string; message?: string; className?: string }) {
  return (
    <EmptyState className={className} icon={PlugZap} title={`Connect ${provider || "this data source"} to use this`}
      description={message || "This feature needs live data from a provider your organisation hasn't connected yet. Nothing is shown rather than estimated."}
      action={<Button asChild><Link href="/settings?tab=integrations">Open integrations</Link></Button>} />
  );
}

export function ErrorState({ error, onRetry, className }: { error: unknown; onRetry?: () => void; className?: string }) {
  if (error instanceof ApiError && error.notConfigured) return <NotConfigured provider={error.body.provider} message={error.body.message} className={className} />;
  if (error instanceof ApiError && error.status === 403) return <EmptyState className={className} icon={Lock} title="You don't have access" description={error.body.message} />;
  return (
    <EmptyState className={className} icon={AlertTriangle} title="This couldn't be loaded" description={errorMessage(error)}
      action={onRetry && <Button variant="secondary" onClick={onRetry}><RefreshCw />Try again</Button>} />
  );
}

export function LoadingRows({ rows = 6, className }: { rows?: number; className?: string }) {
  return <div className={cn("space-y-2 p-4", className)}>{Array.from({ length: rows }).map((_, i) => <Skeleton key={i} className="h-10 w-full" />)}</div>;
}

/* ---------------------------------------------------------------- Charts (lightweight SVG) */
export function Sparkline({ values, tone = "primary", height = 32, className, fill = true }: { values: (number | null)[]; tone?: "primary" | "success" | "danger" | "warning" | "cyan" | "violet"; height?: number; className?: string; fill?: boolean }) {
  const v = values.filter((x): x is number => x != null && Number.isFinite(x));
  const id = React.useId();
  if (v.length < 2) return <div style={{ height }} className={cn("w-full", className)} />;
  const min = Math.min(...v), max = Math.max(...v), span = max - min || 1, W = 120, H = height;
  const pts = v.map((y, i) => [(i / (v.length - 1)) * W, H - 2 - ((y - min) / span) * (H - 4)]);
  const d = pts.map((p, i) => `${i ? "L" : "M"}${p[0].toFixed(1)} ${p[1].toFixed(1)}`).join(" ");
  const color = `rgb(var(--${tone}))`;
  return (
    <svg viewBox={`0 0 ${W} ${H}`} preserveAspectRatio="none" className={cn("w-full overflow-visible", className)} style={{ height }} aria-hidden>
      <defs><linearGradient id={id} x1="0" x2="0" y1="0" y2="1"><stop offset="0%" stopColor={color} stopOpacity="0.22" /><stop offset="100%" stopColor={color} stopOpacity="0" /></linearGradient></defs>
      {fill && <path d={`${d} L${W} ${H} L0 ${H} Z`} fill={`url(#${id})`} />}
      <path d={d} fill="none" stroke={color} strokeWidth="1.6" vectorEffect="non-scaling-stroke" strokeLinejoin="round" />
      <circle cx={pts[pts.length - 1][0]} cy={pts[pts.length - 1][1]} r="2.4" fill={color} />
    </svg>
  );
}

export function ScoreRing({ score, size = 44, stroke = 4, label }: { score: number | null | undefined; size?: number; stroke?: number; label?: string }) {
  const s = score ?? 0, r = (size - stroke) / 2, c = 2 * Math.PI * r, tone = scoreTone(score);
  const color = tone === "neutral" ? "rgb(var(--subtle))" : `rgb(var(--${tone}))`;
  return (
    <div className="relative grid shrink-0 place-items-center" style={{ width: size, height: size }} aria-label={`${label || "Score"} ${score ?? "not available"}`}>
      <svg width={size} height={size} className="-rotate-90">
        <circle cx={size / 2} cy={size / 2} r={r} fill="none" stroke="rgb(var(--surface-3))" strokeWidth={stroke} />
        <circle cx={size / 2} cy={size / 2} r={r} fill="none" stroke={color} strokeWidth={stroke} strokeLinecap="round" strokeDasharray={c} strokeDashoffset={c * (1 - s / 100)} className="transition-[stroke-dashoffset] duration-500" />
      </svg>
      <span className="absolute text-[13px] font-semibold num" style={{ fontSize: size < 40 ? 11 : size > 60 ? 18 : 13, color }}>{score == null ? "—" : Math.round(s)}</span>
    </div>
  );
}

export function ScorePill({ score }: { score: number | null | undefined }) {
  const tone = scoreTone(score);
  return <Badge tone={tone === "neutral" ? "neutral" : tone} className="min-w-[38px] justify-center font-semibold num">{score == null ? "—" : Math.round(score)}</Badge>;
}

export function BarList({ rows, format, max }: { rows: { label: React.ReactNode; value: number; hint?: React.ReactNode; tone?: string }[]; format?: (v: number) => string; max?: number }) {
  const m = max ?? Math.max(1, ...rows.map((r) => r.value));
  return (
    <div className="space-y-2.5">
      {rows.map((r, i) => (
        <div key={i} className="grid grid-cols-[minmax(0,1fr)_auto] items-center gap-x-3 gap-y-1">
          <div className="min-w-0 truncate text-[13px]">{r.label}</div>
          <div className="text-[13px] font-medium num">{format ? format(r.value) : r.value}</div>
          <div className="col-span-2 h-1.5 overflow-hidden rounded-full bg-surface-3"><div className="h-full rounded-full" style={{ width: `${(r.value / m) * 100}%`, background: `rgb(var(--${r.tone || "primary"}))` }} /></div>
        </div>
      ))}
    </div>
  );
}

/* ---------------------------------------------------------------- Metric card */
export function MetricCard({ label, value, icon: Icon, delta, deltaLabel, trend, tone = "primary", tooltip, source, loading, sub, className, href }: {
  label: string; value: React.ReactNode; icon?: LucideIcon; delta?: number | null; deltaLabel?: string; trend?: (number | null)[]; tone?: "primary" | "success" | "danger" | "warning" | "cyan" | "violet";
  tooltip?: React.ReactNode; source?: Source | null; loading?: boolean; sub?: React.ReactNode; className?: string; href?: string;
}) {
  const inner = (
    <Card className={cn("flex h-full flex-col gap-3 p-4 transition-colors", href && "hover:border-line-strong", className)}>
      <div className="flex items-center gap-2">
        {Icon && <span className={cn("grid size-7 place-items-center rounded-lg", `bg-${tone}-soft text-${tone}`)} style={{ background: `rgb(var(--${tone}-soft, var(--primary-soft)))`, color: `rgb(var(--${tone}))` }}><Icon className="size-3.5" /></span>}
        <span className="min-w-0 flex-1 truncate text-[13px] font-medium text-muted">{label}</span>
        {tooltip && <InfoTip content={tooltip} />}
      </div>
      {loading ? <Skeleton className="h-8 w-28" /> : <div className="text-[26px] font-semibold leading-none tracking-tight num">{value}</div>}
      <div className="flex min-h-[20px] items-end justify-between gap-3">
        <div className="flex min-w-0 flex-wrap items-center gap-2 text-xs text-muted">
          {delta != null && Number.isFinite(delta) && (
            <span className={cn("inline-flex items-center gap-0.5 font-medium num", delta >= 0 ? "text-success" : "text-danger")}>
              {delta >= 0 ? <ArrowUpRight className="size-3.5" /> : <ArrowDownRight className="size-3.5" />}{Math.abs(delta).toFixed(1)}%
            </span>
          )}
          {deltaLabel && <span className="truncate">{deltaLabel}</span>}
          {sub}
          {source && <SourceBadge source={source} />}
        </div>
        {trend && trend.filter((x) => x != null).length > 1 && <div className="w-20 shrink-0"><Sparkline values={trend} tone={tone} height={28} /></div>}
      </div>
    </Card>
  );
  return href ? <Link href={href} className="block h-full">{inner}</Link> : inner;
}

